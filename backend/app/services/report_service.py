"""
``ReportService`` -- orchestrates a single ``POST /report`` request end-to-end.

Per the approved Phase 8 design, this composes ``ChatService`` rather than
duplicating session/memory/graph orchestration: a report request is built
into a ``ChatRequest(mode=ChatMode.REPORT, ...)`` and handed to
``ChatService.send_message()``, exactly matching ``schemas.chat``'s own
module docstring describing ``POST /report`` as "a thin convenience
wrapper that issues the same underlying request with ``mode='report'``".
Everything downstream of that -- assembling a ``ReportDocument`` from the
resulting Markdown, exporting it to a concrete file format, and persisting
the result -- is this file's own responsibility.

Two-tier failure handling (approved before implementation began):

* Research-pipeline failures -- anything ``ChatService.send_message()``
  raises (``SessionNotFoundError``, ``GraphExecutionError``,
  ``MaxRetriesExceededError``, ...) -- are never caught here. They
  propagate unchanged out of ``generate_report()``, exactly like
  ``/chat``'s identical failures do, and no ``Report`` row is ever created
  for them (there's nothing yet to attach one to).
* Export-step failures -- either the exporter itself
  (``ReportExportError``, covering both ``ReportTemplateError`` and
  ``ReportRenderingError``) or the subsequent disk write
  (``OSError`` -- disk full, permission denied, ...) -- are caught,
  produce a persisted ``Report`` row with ``status=FAILED`` plus the
  error, and are returned as a normal (if unhappy)
  ``ReportGenerationResponse``, not raised as an HTTP error. An ``OSError``
  is wrapped into a ``ReportRenderingError`` before being handled
  identically to an exporter failure -- from the caller's perspective,
  "the export step didn't produce a downloadable file" is one outcome
  regardless of which of the two actually failed.

``Report`` persistence happens exactly once, after the final outcome
(``COMPLETED`` or ``FAILED``) is already known -- no intermediate
``QUEUED``/``GENERATING`` row. Those two statuses exist on
``ReportGenerationStatus`` for a future asynchronous/queued
implementation (see that enum's own docstring); this synchronous
implementation never returns them, which is documented scope, not a gap.

``get_download()`` (backing ``GET /report/{id}/download``) returns a
plain ``ReportDownload`` dataclass, never the ``Report`` ORM row itself --
keeping the same "services return plain data, never persistence-layer
objects" boundary ``ChatService`` already establishes (it returns
``ChatResponse``, never a ``ConversationTurn`` row). It distinguishes two
different failure meanings, both mapped through exceptions that already
exist rather than new ones:

* The report id itself doesn't exist -- ``ReportRepository.require_by_id()``
  raises ``RecordNotFoundError`` (already maps to 404), propagated
  unchanged. Not caught or re-wrapped here.
* The report exists but has nothing downloadable -- ``status !=
  COMPLETED`` (e.g. a ``FAILED`` report), a missing ``file_path``, or
  (the one genuinely defensive case: the DB row claims a file exists but
  it's gone from disk, e.g. removed out-of-band) the referenced file not
  actually being present -- raises ``ResourceNotFoundError`` (also 404,
  but a semantically distinct case: the identifier was valid, the
  *download* isn't available). Each of the three raises with a message
  naming specifically why, so a client/log reader can't mistake this for
  "that report id was never valid."

Local-filesystem storage only -- ``file_path`` is read directly off the
``Report`` row and opened from local disk. No storage abstraction (object
storage, retention/cleanup policy, presigned URLs) is introduced here;
that would be solving a problem this project doesn't have yet (see
``ReportSettings.output_dir``'s own single-directory design), not a gap
in this file's scope.

Two independent ``database.session()`` units of work happen per request --
none held open across ``ChatService.send_message()`` (real LLM/retrieval/
search work) or the exporter/filesystem step -- mirroring the exact
reasoning ``ChatService`` itself already documents for the same problem.
The first unit of work is entirely inside ``ChatService`` (this file
doesn't open one of its own for it); the second is this file's own single
``Report``-row write, after the outcome is known.

Every identifier this file generates (``report_id``) follows the same
``f"{prefix}-{uuid4().hex[:8]}"`` convention ``ChatService`` already
established for ``session_id``/``message_id``/citation and execution-step
ids -- generated by the service layer, not the repository (no repository
in this codebase generates its own primary keys; see
``ConversationRepository.create_session()``, which takes an
already-generated id as a parameter).
"""

